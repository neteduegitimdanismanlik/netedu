import type { Metadata } from 'next'
import Link from 'next/link'
import { notFound } from 'next/navigation'
import { UNIVERSITIES, byId } from '../index'
import { areaSlug } from '../slugs'

/**
 * Public, unauthenticated overview of one university — every department we
 * hold data for, each linking to its own long-tail page. Pre-rendered at
 * build time: there is nothing personal on this page, so it can be served
 * as plain static HTML and indexed without a login wall.
 */

export function generateStaticParams() {
  return UNIVERSITIES.map((u) => ({ id: u.id }))
}

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }): Promise<Metadata> {
  const { id } = await params
  const u = byId(id)
  if (!u) return {}
  return {
    title: `${u.name} — IB & Turkish Diploma (MEB) Requirements | NetEdu`,
    description: `Verified IB Diploma and Turkish national diploma entry requirements for ${u.name} (${u.city}, ${u.country}), by department. Checked ${u.checkedOn}.`,
  }
}

export default async function UniversityPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params
  const u = byId(id)
  if (!u) return notFound()

  const offered = u.areas.filter((a) => a.offered)

  return (
    <main className="min-h-screen bg-gray-50">
      <nav className="bg-white border-b border-gray-100 px-6 py-4">
        <Link href="/" className="flex items-center gap-2 w-fit">
          <div className="w-8 h-8 bg-indigo-900 rounded-lg flex items-center justify-center">
            <span className="text-white text-sm font-bold">N</span>
          </div>
          <span className="font-semibold text-indigo-900 text-base">NetEdu</span>
        </Link>
      </nav>

      <div className="max-w-3xl mx-auto px-4 py-10">
        <p className="text-xs text-gray-400 mb-2">
          <Link href="/universities" className="hover:text-indigo-700">All universities</Link> / {u.country}
        </p>
        <h1 className="text-3xl font-bold text-gray-900 mb-1">{u.name}</h1>
        <p className="text-gray-500 mb-6">
          {u.city}, {u.country} · {u.cycle} · requirements checked {u.checkedOn}
        </p>

        {u.ibNote && (
          <div className="bg-white border border-gray-100 rounded-xl p-4 mb-6 text-sm text-gray-600">
            {u.ibNote}
          </div>
        )}

        <div className="bg-indigo-900 text-white rounded-2xl p-5 mb-8 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
          <div>
            <p className="font-semibold text-sm mb-1">See where you actually stand at {u.name}</p>
            <p className="text-xs text-indigo-200">
              This page is generated by NetEdu's matching engine from the same data your personal shortlist
              uses. Enter your IB points, HL subjects or Turkish diploma average to get your Reach / Match /
              Safety verdict for each department below — free.
            </p>
          </div>
          <Link
            href="/auth"
            className="shrink-0 bg-white text-indigo-900 px-5 py-2.5 rounded-xl text-sm font-medium hover:bg-indigo-50 text-center"
          >
            Check my fit →
          </Link>
        </div>

        <h2 className="text-sm font-semibold text-gray-400 uppercase tracking-wide mb-3">Departments</h2>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 mb-10">
          {offered.map((a) => (
            <Link
              key={a.area}
              href={`/universities/${u.id}/${areaSlug(a.area)}`}
              className="bg-white border border-gray-100 rounded-xl p-4 hover:border-indigo-200 hover:shadow-sm transition-all"
            >
              <p className="font-medium text-gray-900 text-sm">{a.course || a.area}</p>
              <p className="text-xs text-gray-400 mt-1">
                {a.ibPoints ? `${a.ibPoints} IB points` : a.mebAccepted ? 'Turkish diploma accepted' : 'Requirements inside'}
                {a.ibHl ? ` · HL ${a.ibHl}` : ''}
              </p>
            </Link>
          ))}
        </div>

        {u.gaps?.length ? (
          <div className="text-xs text-gray-400 border-t border-gray-200 pt-4">
            <p className="font-medium text-gray-500 mb-1">What we haven't verified here:</p>
            <ul className="space-y-0.5">
              {u.gaps.map((g, i) => <li key={i}>· {g}</li>)}
            </ul>
          </div>
        ) : null}
      </div>
    </main>
  )
}
